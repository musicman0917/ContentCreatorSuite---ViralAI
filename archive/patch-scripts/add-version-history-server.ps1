# add-version-history-server.ps1
# Adds content version history endpoints so re-uploaded cuts can be compared.
# Storage defaults to D:\ViralAudit history (override with VIRAL_HISTORY_DIR in .env)
$file = "D:\Coding\ViralAI\viral-audit-server.cjs"

if (-not (Test-Path $file)) { Write-Host "ERROR: File not found at $file" -ForegroundColor Red; exit 1 }
Copy-Item $file "$file.verbak" -Force
Write-Host "Backup written to $file.verbak" -ForegroundColor DarkGray

$content = [System.IO.File]::ReadAllText($file)
$content = $content.Replace("`r`n", "`n")

$block = [System.Text.StringBuilder]::new()
[void]$block.Append('// ─── Content Version History ─────────────────────────────────────────────────')
[void]$block.Append("`n")
[void]$block.Append('// Stores analysis snapshots so a re-uploaded cut can be compared to its predecessor.')
[void]$block.Append("`n")
[void]$block.Append('const HISTORY_DIR = process.env.VIRAL_HISTORY_DIR || "D:\\ViralAudit history";')
[void]$block.Append("`n")
[void]$block.Append('')
[void]$block.Append("`n")
[void]$block.Append('if (!fs.existsSync(HISTORY_DIR)) {')
[void]$block.Append("`n")
[void]$block.Append('  fs.mkdirSync(HISTORY_DIR, { recursive: true });')
[void]$block.Append("`n")
[void]$block.Append('  console.log(`[history] Created history dir: ${HISTORY_DIR}`);')
[void]$block.Append("`n")
[void]$block.Append('}')
[void]$block.Append("`n")
[void]$block.Append('')
[void]$block.Append("`n")
[void]$block.Append('function safeContentId(id) {')
[void]$block.Append("`n")
[void]$block.Append('  return /^[a-zA-Z0-9_-]{1,64}$/.test(String(id || "")) ? String(id) : null;')
[void]$block.Append("`n")
[void]$block.Append('}')
[void]$block.Append("`n")
[void]$block.Append('')
[void]$block.Append("`n")
[void]$block.Append('function historyPath(contentId) {')
[void]$block.Append("`n")
[void]$block.Append('  return path.join(HISTORY_DIR, `${contentId}.json`);')
[void]$block.Append("`n")
[void]$block.Append('}')
[void]$block.Append("`n")
[void]$block.Append('')
[void]$block.Append("`n")
[void]$block.Append('function readContentItem(contentId) {')
[void]$block.Append("`n")
[void]$block.Append('  const p = historyPath(contentId);')
[void]$block.Append("`n")
[void]$block.Append('  if (!fs.existsSync(p)) return null;')
[void]$block.Append("`n")
[void]$block.Append('  try { return JSON.parse(fs.readFileSync(p, "utf8")); } catch { return null; }')
[void]$block.Append("`n")
[void]$block.Append('}')
[void]$block.Append("`n")
[void]$block.Append('')
[void]$block.Append("`n")
[void]$block.Append('// Snapshots are text only - base64 frames would balloon these files')
[void]$block.Append("`n")
[void]$block.Append('function trimVersionPayload(v) {')
[void]$block.Append("`n")
[void]$block.Append('  return {')
[void]$block.Append("`n")
[void]$block.Append('    versionId: uuidv4().slice(0, 8),')
[void]$block.Append("`n")
[void]$block.Append('    savedAt: new Date().toISOString(),')
[void]$block.Append("`n")
[void]$block.Append('    label: String(v.label || "").slice(0, 200),')
[void]$block.Append("`n")
[void]$block.Append('    filename: String(v.filename || "").slice(0, 200),')
[void]$block.Append("`n")
[void]$block.Append('    duration: Number(v.duration) || 0,')
[void]$block.Append("`n")
[void]$block.Append('    platform: v.platform || null,')
[void]$block.Append("`n")
[void]$block.Append('    niche: v.niche || null,')
[void]$block.Append("`n")
[void]$block.Append('    isTikTokShop: !!v.isTikTokShop,')
[void]$block.Append("`n")
[void]$block.Append('    isLiveClip: !!v.isLiveClip,')
[void]$block.Append("`n")
[void]$block.Append('    score: Number(v.score) || 0,')
[void]$block.Append("`n")
[void]$block.Append('    hookScore: Number(v.hookScore) || 0,')
[void]$block.Append("`n")
[void]$block.Append('    wordCount: Number(v.wordCount) || 0,')
[void]$block.Append("`n")
[void]$block.Append('    transcript: String(v.transcript || "").slice(0, 4000),')
[void]$block.Append("`n")
[void]$block.Append('    flags: Array.isArray(v.flags) ? v.flags.slice(0, 30).map(f => ({ severity: f.severity, msg: String(f.msg || "").slice(0, 300) })) : [],')
[void]$block.Append("`n")
[void]$block.Append('    positives: Array.isArray(v.positives) ? v.positives.slice(0, 30).map(p => String(p).slice(0, 300)) : [],')
[void]$block.Append("`n")
[void]$block.Append('    holisticAnalysis: String(v.holisticAnalysis || "").slice(0, 6000),')
[void]$block.Append("`n")
[void]$block.Append('    frameNotes: Array.isArray(v.frameNotes) ? v.frameNotes.slice(0, 10).map(f => ({ label: f.label, analysis: String(f.analysis || "").slice(0, 500) })) : [],')
[void]$block.Append("`n")
[void]$block.Append('  };')
[void]$block.Append("`n")
[void]$block.Append('}')
[void]$block.Append("`n")
[void]$block.Append('')
[void]$block.Append("`n")
[void]$block.Append('// Cheap bag-of-words overlap, used only to pre-select a likely match in the UI')
[void]$block.Append("`n")
[void]$block.Append('function transcriptSimilarity(a, b) {')
[void]$block.Append("`n")
[void]$block.Append('  const norm = s => String(s || "").toLowerCase().replace(/[^a-z0-9 ]/g, " ").split(/\s+/).filter(w => w.length > 3);')
[void]$block.Append("`n")
[void]$block.Append('  const A = new Set(norm(a).slice(0, 400));')
[void]$block.Append("`n")
[void]$block.Append('  const B = new Set(norm(b).slice(0, 400));')
[void]$block.Append("`n")
[void]$block.Append('  if (A.size === 0 || B.size === 0) return 0;')
[void]$block.Append("`n")
[void]$block.Append('  let shared = 0;')
[void]$block.Append("`n")
[void]$block.Append('  for (const w of A) if (B.has(w)) shared++;')
[void]$block.Append("`n")
[void]$block.Append('  return shared / Math.min(A.size, B.size);')
[void]$block.Append("`n")
[void]$block.Append('}')
[void]$block.Append("`n")
[void]$block.Append('')
[void]$block.Append("`n")
[void]$block.Append('app.get("/content/list", (req, res) => {')
[void]$block.Append("`n")
[void]$block.Append('  try {')
[void]$block.Append("`n")
[void]$block.Append('    const files = fs.readdirSync(HISTORY_DIR).filter(f => f.endsWith(".json"));')
[void]$block.Append("`n")
[void]$block.Append('    const items = files.map(f => {')
[void]$block.Append("`n")
[void]$block.Append('      try {')
[void]$block.Append("`n")
[void]$block.Append('        const item = JSON.parse(fs.readFileSync(path.join(HISTORY_DIR, f), "utf8"));')
[void]$block.Append("`n")
[void]$block.Append('        const latest = item.versions?.[item.versions.length - 1];')
[void]$block.Append("`n")
[void]$block.Append('        return {')
[void]$block.Append("`n")
[void]$block.Append('          contentId: item.contentId,')
[void]$block.Append("`n")
[void]$block.Append('          title: item.title,')
[void]$block.Append("`n")
[void]$block.Append('          versionCount: item.versions?.length || 0,')
[void]$block.Append("`n")
[void]$block.Append('          lastSaved: latest?.savedAt || item.createdAt,')
[void]$block.Append("`n")
[void]$block.Append('          latestScore: latest?.score ?? null,')
[void]$block.Append("`n")
[void]$block.Append('          platform: latest?.platform || null,')
[void]$block.Append("`n")
[void]$block.Append('          latestTranscript: String(latest?.transcript || "").slice(0, 1200),')
[void]$block.Append("`n")
[void]$block.Append('        };')
[void]$block.Append("`n")
[void]$block.Append('      } catch { return null; }')
[void]$block.Append("`n")
[void]$block.Append('    }).filter(Boolean).sort((a, b) => String(b.lastSaved).localeCompare(String(a.lastSaved)));')
[void]$block.Append("`n")
[void]$block.Append('    res.json({ items });')
[void]$block.Append("`n")
[void]$block.Append('  } catch (e) {')
[void]$block.Append("`n")
[void]$block.Append('    res.status(500).json({ error: e.message });')
[void]$block.Append("`n")
[void]$block.Append('  }')
[void]$block.Append("`n")
[void]$block.Append('});')
[void]$block.Append("`n")
[void]$block.Append('')
[void]$block.Append("`n")
[void]$block.Append('// Suggests which existing item a new transcript most likely belongs to')
[void]$block.Append("`n")
[void]$block.Append('app.post("/content/suggest-match", express.json({ limit: "2mb" }), (req, res) => {')
[void]$block.Append("`n")
[void]$block.Append('  try {')
[void]$block.Append("`n")
[void]$block.Append('    const transcript = String(req.body?.transcript || "");')
[void]$block.Append("`n")
[void]$block.Append('    if (!transcript.trim()) return res.json({ suggestion: null });')
[void]$block.Append("`n")
[void]$block.Append('    const files = fs.readdirSync(HISTORY_DIR).filter(f => f.endsWith(".json"));')
[void]$block.Append("`n")
[void]$block.Append('    let best = null;')
[void]$block.Append("`n")
[void]$block.Append('    for (const f of files) {')
[void]$block.Append("`n")
[void]$block.Append('      try {')
[void]$block.Append("`n")
[void]$block.Append('        const item = JSON.parse(fs.readFileSync(path.join(HISTORY_DIR, f), "utf8"));')
[void]$block.Append("`n")
[void]$block.Append('        const latest = item.versions?.[item.versions.length - 1];')
[void]$block.Append("`n")
[void]$block.Append('        if (!latest) continue;')
[void]$block.Append("`n")
[void]$block.Append('        const score = transcriptSimilarity(transcript, latest.transcript);')
[void]$block.Append("`n")
[void]$block.Append('        if (!best || score > best.similarity) {')
[void]$block.Append("`n")
[void]$block.Append('          best = { contentId: item.contentId, title: item.title, versionCount: item.versions.length, similarity: score };')
[void]$block.Append("`n")
[void]$block.Append('        }')
[void]$block.Append("`n")
[void]$block.Append('      } catch {}')
[void]$block.Append("`n")
[void]$block.Append('    }')
[void]$block.Append("`n")
[void]$block.Append('    res.json({ suggestion: best && best.similarity >= 0.35 ? best : null });')
[void]$block.Append("`n")
[void]$block.Append('  } catch (e) {')
[void]$block.Append("`n")
[void]$block.Append('    res.status(500).json({ error: e.message });')
[void]$block.Append("`n")
[void]$block.Append('  }')
[void]$block.Append("`n")
[void]$block.Append('});')
[void]$block.Append("`n")
[void]$block.Append('')
[void]$block.Append("`n")
[void]$block.Append('app.get("/content/item/:contentId", (req, res) => {')
[void]$block.Append("`n")
[void]$block.Append('  const id = safeContentId(req.params.contentId);')
[void]$block.Append("`n")
[void]$block.Append('  if (!id) return res.status(400).json({ error: "Invalid content id." });')
[void]$block.Append("`n")
[void]$block.Append('  const item = readContentItem(id);')
[void]$block.Append("`n")
[void]$block.Append('  if (!item) return res.status(404).json({ error: "Content item not found." });')
[void]$block.Append("`n")
[void]$block.Append('  res.json(item);')
[void]$block.Append("`n")
[void]$block.Append('});')
[void]$block.Append("`n")
[void]$block.Append('')
[void]$block.Append("`n")
[void]$block.Append('app.post("/content/save-version", express.json({ limit: "5mb" }), (req, res) => {')
[void]$block.Append("`n")
[void]$block.Append('  try {')
[void]$block.Append("`n")
[void]$block.Append('    const { contentId, title, version } = req.body || {};')
[void]$block.Append("`n")
[void]$block.Append('    if (!version) return res.status(400).json({ error: "No version payload supplied." });')
[void]$block.Append("`n")
[void]$block.Append('')
[void]$block.Append("`n")
[void]$block.Append('    let item = null;')
[void]$block.Append("`n")
[void]$block.Append('    let id = safeContentId(contentId);')
[void]$block.Append("`n")
[void]$block.Append('')
[void]$block.Append("`n")
[void]$block.Append('    if (id) {')
[void]$block.Append("`n")
[void]$block.Append('      item = readContentItem(id);')
[void]$block.Append("`n")
[void]$block.Append('      if (!item) return res.status(404).json({ error: "Content item not found - it may have been deleted." });')
[void]$block.Append("`n")
[void]$block.Append('    } else {')
[void]$block.Append("`n")
[void]$block.Append('      id = uuidv4().slice(0, 12);')
[void]$block.Append("`n")
[void]$block.Append('      item = { contentId: id, title: String(title || "Untitled content").slice(0, 200), createdAt: new Date().toISOString(), versions: [] };')
[void]$block.Append("`n")
[void]$block.Append('    }')
[void]$block.Append("`n")
[void]$block.Append('')
[void]$block.Append("`n")
[void]$block.Append('    const previousVersion = item.versions.length > 0 ? item.versions[item.versions.length - 1] : null;')
[void]$block.Append("`n")
[void]$block.Append('    const snapshot = trimVersionPayload(version);')
[void]$block.Append("`n")
[void]$block.Append('    snapshot.versionNumber = item.versions.length + 1;')
[void]$block.Append("`n")
[void]$block.Append('    item.versions.push(snapshot);')
[void]$block.Append("`n")
[void]$block.Append('    if (item.versions.length > 25) item.versions = item.versions.slice(-25);')
[void]$block.Append("`n")
[void]$block.Append('')
[void]$block.Append("`n")
[void]$block.Append('    fs.writeFileSync(historyPath(id), JSON.stringify(item, null, 2), "utf8");')
[void]$block.Append("`n")
[void]$block.Append('    console.log(`[history] Saved "${item.title}" v${snapshot.versionNumber} (score ${snapshot.score})`);')
[void]$block.Append("`n")
[void]$block.Append('')
[void]$block.Append("`n")
[void]$block.Append('    res.json({ contentId: id, title: item.title, versionNumber: snapshot.versionNumber, currentVersion: snapshot, previousVersion });')
[void]$block.Append("`n")
[void]$block.Append('  } catch (e) {')
[void]$block.Append("`n")
[void]$block.Append('    console.error("[history] Save failed:", e.message);')
[void]$block.Append("`n")
[void]$block.Append('    res.status(500).json({ error: e.message });')
[void]$block.Append("`n")
[void]$block.Append('  }')
[void]$block.Append("`n")
[void]$block.Append('});')
$block = $block.ToString()

$anchor = [System.Text.StringBuilder]::new()
[void]$anchor.Append('app.use((err, req, res, next) => {')
$anchor = $anchor.ToString()

if ($content.Contains("/content/save-version")) { Write-Host "Version history already installed - nothing to do." -ForegroundColor Yellow; exit 0 }

if ($content.Contains($anchor)) {
  $content = $content.Replace($anchor, $block + "`n`n" + $anchor)
  Write-Host "[1/1] Version history endpoints added" -ForegroundColor Green
} else {
  Write-Host "[1/1] SKIP: error handler anchor not found - nothing written" -ForegroundColor Red
  exit 1
}

$utf8NoBom = New-Object System.Text.UTF8Encoding $false
[System.IO.File]::WriteAllText($file, $content, $utf8NoBom)
Write-Host ""
Write-Host "Done. Restart backend: pm2 restart viral-audit-server" -ForegroundColor Cyan